// Команда bootstrap — one-shot засев корневых данных сервиса.
//
// Зачем отдельный бинарь, а не HTTP-эндпоинт и не «сделай руками через UI»:
// корневые данные упираются в циклическую зависимость прав. Чтобы выдать
// первому пользователю роль администратора, нужен пользователь; чтобы создать
// пользователя, нужно подразделение; чтобы создать подразделение, нужны права
// администратора. Стенд «с нуля» в такой системе не собирается вообще.
//
// Разрывает цикл только запись в обход HTTP и проверки доступа — то есть
// напрямую через слой хранилища сервиса-владельца. Именно поэтому команда
// живёт ВНУТРИ владельца данных, а не в отдельном сервисе-сеятеле: чужую
// схему никто не трогает.
//
// Команда обязана быть идемпотентной и завершаться: она запускается при каждом
// подъёме стенда и в CI.
//
//	go run ./cmd/bootstrap
package main

import (
	"context"
	"os"
	"os/signal"
	"syscall"

	"roleplay/gotemplate/internal/app"
)

func main() {
	ctx, cancel := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer cancel()

	if err := app.Bootstrap(ctx); err != nil {
		// Ненулевой код возврата обязателен: в compose и CI неуспешный засев
		// должен останавливать подъём стенда, а не оставлять его наполовину
		// заполненным.
		os.Stderr.WriteString("bootstrap: " + err.Error() + "\n")
		os.Exit(1)
	}
}
